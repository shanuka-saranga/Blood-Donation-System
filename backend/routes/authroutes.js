const express = require("express");
const router = express.Router();
const { register, login, updateProfile, updateDonorDetails, changePassword, checkEligibility, markDonation, getDonations, getLatestDonation, getDonationCamps, bookCampAppointment, getMyCampAppointments, getNotifications, markNotificationsRead, createAdminNotification, updateBloodInventory, updateCampAppointment, deleteCampAppointment, reviewCampAppointment, getDonorActivity, getAdminSummary, createDonationCamp } = require("../controllers/authcontroller");
const authenticate = require("../middleware/authenticate");
const authorizeAdmin = require("../middleware/authorizeAdmin");
const authorizeMedicalStaff = require("../middleware/authorizeMedicalStaff");
const authorizeCampOrganizer = require("../middleware/authorizeCampOrganizer");
const { updateAdminUser, deleteAdminUser } = require("../controllers/authcontroller");
const { getMedicalSummary, createMedicalAssessment, deleteMedicalAssessment, getCampOrganizerSummary, createOrganizerCamp, updateOrganizerAppointment, addCampVolunteer, updateCampMetrics, reviewOrganizerCamp, reviewCampRequest } = require("../controllers/authcontroller");

router.post("/register", register);
router.post("/login", login);
router.put("/profile", authenticate, updateProfile);
router.put("/donor-details", authenticate, updateDonorDetails);
router.put("/change-password", authenticate, changePassword);
router.get("/eligibility", authenticate, checkEligibility);
router.post("/donations", authenticate, markDonation);
router.get("/donations", authenticate, getDonations);
router.get("/donations/latest", authenticate, getLatestDonation);
router.get("/camps", authenticate, getDonationCamps);
router.post("/camps/:campId/appointments", authenticate, bookCampAppointment);
router.get("/appointments", authenticate, getMyCampAppointments);
router.get("/notifications", authenticate, getNotifications);
router.put("/notifications/read", authenticate, markNotificationsRead);
router.post("/admin/notifications", authenticate, authorizeAdmin, createAdminNotification);
router.put("/admin/inventory/:bloodGroup", authenticate, authorizeAdmin, updateBloodInventory);
router.put("/appointments/:appointmentId", authenticate, updateCampAppointment);
router.delete("/appointments/:appointmentId", authenticate, deleteCampAppointment);
router.patch("/admin/appointments/:appointmentId", authenticate, authorizeAdmin, reviewCampAppointment);
router.get("/activity", authenticate, getDonorActivity);
router.get("/admin-summary", authenticate, authorizeAdmin, getAdminSummary);
router.post("/admin/camps", authenticate, authorizeAdmin, createDonationCamp);
router.put("/admin/users/:userId", authenticate, authorizeAdmin, updateAdminUser);
router.delete("/admin/users/:userId", authenticate, authorizeAdmin, deleteAdminUser);
router.get("/medical/summary", authenticate, authorizeMedicalStaff, getMedicalSummary);
router.post("/medical/assessments", authenticate, authorizeMedicalStaff, createMedicalAssessment);
router.delete("/medical/assessments/:assessmentId", authenticate, authorizeMedicalStaff, deleteMedicalAssessment);
router.get("/camp-organizer/summary", authenticate, authorizeCampOrganizer, getCampOrganizerSummary);
router.post("/camp-organizer/camps", authenticate, authorizeCampOrganizer, createOrganizerCamp);
router.patch("/camp-organizer/appointments/:appointmentId", authenticate, authorizeCampOrganizer, updateOrganizerAppointment);
router.post("/camp-organizer/camps/:campId/volunteers", authenticate, authorizeCampOrganizer, addCampVolunteer);
router.patch("/camp-organizer/camps/:campId/metrics", authenticate, authorizeCampOrganizer, updateCampMetrics);
router.patch("/admin/camps/:campId", authenticate, authorizeAdmin, reviewOrganizerCamp);
router.patch("/admin/camp-requests/:requestId", authenticate, authorizeAdmin, reviewCampRequest);

module.exports = router;
